import fs from "node:fs";
import path from "node:path";
import { parse } from "yaml";
import type { Plugin } from "vite";
import { parsePostFile, type PostSource } from "./posts/parse.ts";
import { validatePosts } from "./posts/validate.ts";
import { createRenderer } from "./posts/render.ts";

const ROOT = process.cwd();
const POSTS_DIR = path.join(ROOT, "posts");
const STATIC_DIR = path.join(ROOT, "static");
const PROJECTS_FILE = path.join(ROOT, "projects/en.yaml");
const OUT_DIR = path.join(ROOT, "src/lib/server/feed/generated");
const OUT_FILE = path.join(OUT_DIR, "posts.ts");
const SITE_URL = "https://thelukez.com";

type Render = (markdown: string) => string;

function readSources(): { sources: PostSource[]; problems: string[] } {
  if (!fs.existsSync(POSTS_DIR)) return { sources: [], problems: [] };
  const sources: PostSource[] = [];
  const problems: string[] = [];
  for (const file of fs
    .readdirSync(POSTS_DIR)
    .filter((f) => f.endsWith(".md"))
    .sort()) {
    try {
      sources.push(parsePostFile(file, fs.readFileSync(path.join(POSTS_DIR, file), "utf-8")));
    } catch (err) {
      problems.push((err as Error).message);
    }
  }
  return { sources, problems };
}

function imageSize(src: string): number | null {
  try {
    return fs.statSync(path.join(STATIC_DIR, src)).size;
  } catch {
    return null;
  }
}

/** Returns the problems found; writes the output only when there are none. */
function generate(render: Render): string[] {
  const { sources, problems } = readSources();
  const en = parse(fs.readFileSync(PROJECTS_FILE, "utf-8")) as { projects?: { id: string }[] };
  const projectIds = new Set((en.projects ?? []).map((p) => p.id));
  problems.push(...validatePosts(sources, { projectIds, imageSize }));
  if (problems.length) return problems;

  const posts = sources
    .filter((s) => !s.draft)
    .map((s) => {
      const date = new Date(s.date);
      return {
        slug: s.slug,
        title: s.title,
        date: date.toISOString(),
        dateMs: date.getTime(),
        summary: s.summary,
        project: s.project,
        image: s.image ? { src: SITE_URL + s.image.src, alt: s.image.alt } : null,
        updated: s.updated ? new Date(s.updated).toISOString() : null,
        html: render(s.body),
      };
    })
    .sort((a, b) => b.dateMs - a.dateMs || (a.slug < b.slug ? -1 : a.slug > b.slug ? 1 : 0));

  const output = `// Auto-generated by vite-plugins/generate-posts.ts from posts/*.md. Do not edit.
import type { Post } from "../types.ts";

export const posts: Post[] = ${JSON.stringify(posts, null, 2)};
`;
  fs.mkdirSync(OUT_DIR, { recursive: true });
  fs.writeFileSync(OUT_FILE, output);
  fs.writeFileSync(path.join(OUT_DIR, ".gitignore"), "*\n");
  console.log(`[generate-posts] generated ${posts.length} posts (${sources.length - posts.length} drafts)`);
  return [];
}

export function generatePostsPlugin(): Plugin {
  let command: "build" | "serve" = "serve";
  let renderer: Promise<Render> | undefined;
  const getRenderer = () => (renderer ??= createRenderer(SITE_URL));

  return {
    name: "generate-posts",
    configResolved(config) {
      command = config.command;
    },
    async buildStart() {
      const problems = generate(await getRenderer());
      this.addWatchFile(POSTS_DIR);
      if (!problems.length) return;
      const message = `[generate-posts] invalid posts:\n${problems.map((p) => `  - ${p}`).join("\n")}`;
      if (command === "build") this.error(message);
      console.error(message);
      // Dev without a previous output: write an empty list so the app still starts.
      if (!fs.existsSync(OUT_FILE)) {
        fs.mkdirSync(OUT_DIR, { recursive: true });
        fs.writeFileSync(
          OUT_FILE,
          `import type { Post } from "../types.ts";\n\nexport const posts: Post[] = [];\n`,
        );
        fs.writeFileSync(path.join(OUT_DIR, ".gitignore"), "*\n");
      }
    },
    async handleHotUpdate(ctx) {
      const file = path.normalize(ctx.file);
      if (!file.startsWith(path.normalize(POSTS_DIR)) && !file.startsWith(path.normalize(PROJECTS_FILE)))
        return;

      const problems = generate(await getRenderer());
      if (problems.length) {
        console.error(`[generate-posts] invalid posts:\n${problems.map((p) => `  - ${p}`).join("\n")}`);
        return [];
      }
      const mods = ctx.server.moduleGraph.getModulesByFile(OUT_FILE);
      if (!mods) return [];
      for (const mod of mods) ctx.server.moduleGraph.invalidateModule(mod);
      return [...mods, ...ctx.modules];
    },
  };
}
